    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    ; Runtime type check: if both operands look like pointers, concat strings
    call new_label
    mov r15, rax           ; r15 = int_add label
    call new_label
    push rax               ; stack: done label
    ; emit: cmp rax, 0x400000 / jb .Lint_add
