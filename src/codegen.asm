; ============================================================
; out_str — Write null-terminated string to output buffer
; rdi = string
; ============================================================
out_str:
    push rbx
    mov rbx, [out_pos]
.loop:
    movzx eax, byte [rdi]
    cmp al, 0
    je .done
    mov [out_buf + rbx], al
    inc rbx
    inc rdi
    jmp .loop
.done:
    mov [out_pos], rbx
    pop rbx
    ret

; ============================================================
; out_n — Write N bytes from rsi to output buffer
; rsi = source, rcx = count
; ============================================================
out_n:
    push rbx
    mov rbx, [out_pos]
.loop:
    cmp rcx, 0
    je .done
    movzx eax, byte [rsi]
    mov [out_buf + rbx], al
    inc rbx
    inc rsi
    dec rcx
    jmp .loop
.done:
    mov [out_pos], rbx
    pop rbx
    ret

; ============================================================
; out_int — Write decimal integer to output buffer
; rdi = integer value
; ============================================================
out_int:
    push rbp
    mov rbp, rsp
    push rbx
    sub rsp, 24

    mov rax, rdi
    xor r8, r8               ; sign flag
    cmp rax, 0
    jge .pos
    neg rax
    mov r8, 1
.pos:
    lea rbx, [rsp + 23]
    mov byte [rbx], 0
.loop:
    dec rbx
    xor rdx, rdx
    mov rcx, 10
    div rcx
    add dl, '0'
    mov [rbx], dl
    cmp rax, 0
    jne .loop
    cmp r8, 1
    jne .emit
    dec rbx
    mov byte [rbx], '-'
.emit:
    mov rdi, rbx
    call out_str

    add rsp, 24
    pop rbx
    pop rbp
    ret

; ============================================================
; data_str — Write to data section buffer (same API as out_str)
; ============================================================
data_str:
    push rbx
    mov rbx, [data_pos]
.loop:
    movzx eax, byte [rdi]
    cmp al, 0
    je .done
    mov [data_buf + rbx], al
    inc rbx
    inc rdi
    jmp .loop
.done:
    mov [data_pos], rbx
    pop rbx
    ret

; ============================================================
; data_n — Write N bytes to data buffer
; ============================================================
data_n:
    push rbx
    mov rbx, [data_pos]
.loop:
    cmp rcx, 0
    je .done
    movzx eax, byte [rsi]
    mov [data_buf + rbx], al
    inc rbx
    inc rsi
    dec rcx
    jmp .loop
.done:
    mov [data_pos], rbx
    pop rbx
    ret

; data_int — Write integer to data buffer
data_int:
    push rbp
    mov rbp, rsp
    push rbx
    sub rsp, 24
    mov rax, rdi
    lea rbx, [rsp + 23]
    mov byte [rbx], 0
.loop:
    dec rbx
    xor rdx, rdx
    mov rcx, 10
    div rcx
    add dl, '0'
    mov [rbx], dl
    cmp rax, 0
    jne .loop
    mov rdi, rbx
    call data_str
    add rsp, 24
    pop rbx
    pop rbp
    ret

; ============================================================
; bss_str / bss_n — Write to BSS section buffer
; ============================================================
bss_str:
    push rbx
    mov rbx, [bss_pos]
.loop:
    movzx eax, byte [rdi]
    cmp al, 0
    je .done
    mov [bss_buf + rbx], al
    inc rbx
    inc rdi
    jmp .loop
.done:
    mov [bss_pos], rbx
    pop rbx
    ret

bss_n:
    push rbx
    mov rbx, [bss_pos]
.loop:
    cmp rcx, 0
    je .done
    movzx eax, byte [rsi]
    mov [bss_buf + rbx], al
    inc rbx
    inc rsi
    dec rcx
    jmp .loop
.done:
    mov [bss_pos], rbx
    pop rbx
    ret

; ============================================================
; new_label — Returns unique label number in rax
; ============================================================
new_label:
    mov rax, [label_cnt]
    inc qword [label_cnt]
    ret

; ============================================================
; out_label_ref — Emit ".Lnn" to output buffer
; rdi = label number
; ============================================================
out_label_ref:
    push rdi
    mov rdi, frag_label_pfx
    call out_str
    pop rdi
    call out_int
    ret

; ============================================================
; out_label_def — Emit ".Lnn:" + newline
; ============================================================
out_label_def:
    push rdi
    mov rdi, frag_label_pfx
    call out_str
    pop rdi
    push rdi
    call out_int
    mov rdi, frag_colon
    call out_str
    pop rdi
    ret

; ============================================================
; Token stream access (reads from lexer's token buffer)
; ============================================================
extern lexer_get_token, lexer_token_count

; cg_peek — Get current token pointer
cg_peek:
    mov rdi, [cg_pos]
    call lexer_get_token
    ret

; cg_advance — Consume and return current token
cg_advance:
    mov rdi, [cg_pos]
    call lexer_get_token
    inc qword [cg_pos]
    ret

; cg_skip_nl — Skip newline tokens
cg_skip_nl:
.loop:
    call cg_peek
    movzx ecx, byte [rax]
    cmp cl, TOK_NEWLINE
    jne .done
    call cg_advance
    jmp .loop
.done:
    ret

; cg_tok_type — Return type of current token in al
cg_tok_type:
    call cg_peek
    movzx eax, byte [rax]
    ret

; cg_tok_sub — Return subtype of current token in al
cg_tok_sub:
    call cg_peek
    movzx eax, byte [rax + 1]
    ret

; cg_is_kw — Check if current token matches keyword
; rdi = keyword text, rsi = length
; Returns: rax = 1 match, 0 no
cg_is_kw:
    push r12
    push r13
    mov r12, rdi
    mov r13, rsi
    call cg_peek
    movzx ecx, byte [rax]
    cmp cl, TOK_KEYWORD
    jne .no
    mov ecx, [rax + 4]
    cmp rcx, r13
    jne .no
    mov rdi, [rax + 8]
    mov rsi, r12
    mov rcx, r13
.cmp:
    cmp rcx, 0
    je .yes
    movzx eax, byte [rdi]
    cmp al, [rsi]
    jne .no
    inc rdi
    inc rsi
    dec rcx
    jmp .cmp
.yes:
    mov rax, 1
    pop r13
    pop r12
    ret
.no:
    xor rax, rax
    pop r13
    pop r12
    ret

; ============================================================
; register_string — Add string literal to data section
; rsi = text pointer, rcx = length
; Returns: rax = string ID
; ============================================================
register_string:
    push r12
    push r13
    mov r12, [str_count]
    mov r13, rcx             ; save string length
    mov [str_ptrs + r12 * 8], rsi
    mov [str_lens + r12 * 8], rcx
    mov [str_ids + r12 * 8], r12

    ; Emit: _sNN db "text", 0
    push rcx
    push rsi
    mov rdi, frag_str_pfx
    call data_str
    mov rdi, r12
    call data_int
    mov rdi, frag_db
    call data_str
    pop rsi
    pop rcx

    ; Opening quote
    mov rbx, [data_pos]
    mov byte [data_buf + rbx], '"'
    inc rbx
    mov [data_pos], rbx

    ; String text — escape newlines/tabs for NASM
    push r14
    mov r14, rcx             ; remaining length
.str_byte_loop:
    cmp r14, 0
    je .str_bytes_done
    movzx eax, byte [rsi]
    cmp al, 10
    je .str_newline
    cmp al, 9
    je .str_tab
    cmp al, 13
    je .str_cr
    ; Normal printable byte
    mov rbx, [data_pos]
    mov [data_buf + rbx], al
    inc rbx
    mov [data_pos], rbx
    inc rsi
    dec r14
    jmp .str_byte_loop
.str_newline:
    push rsi
    mov rdi, frag_str_esc_nl
    call data_str
    pop rsi
    inc rsi
    dec r14
    jmp .str_byte_loop
.str_tab:
    push rsi
    mov rdi, frag_str_esc_tab
    call data_str
    pop rsi
    inc rsi
    dec r14
    jmp .str_byte_loop
.str_cr:
    push rsi
    mov rdi, frag_str_esc_cr
    call data_str
    pop rsi
    inc rsi
    dec r14
    jmp .str_byte_loop
.str_bytes_done:
    pop r14

    ; Closing quote
    mov rbx, [data_pos]
    mov byte [data_buf + rbx], '"'
    inc rbx
    mov [data_pos], rbx
    ; , 0\n
    mov rdi, frag_comma_0
    call data_str

    ; Emit: _sNN_len equ <length>
    mov rdi, frag_str_pfx
    call data_str
    mov rdi, r12
    call data_int
    ; Emit "_len equ <length>"
    mov rdi, frag_len_equ
    call data_str
    mov rdi, r13             ; string length
    call data_int
    ; newline
    mov rbx, [data_pos]
    mov byte [data_buf + rbx], 10
    inc rbx
    mov [data_pos], rbx

    mov rax, r12
    inc qword [str_count]
    pop r13
    pop r12
    ret

; ============================================================
; register_var — Register variable, emit in BSS
; rsi = name pointer, rcx = length
; Returns: rax = var ID
; ============================================================
register_var:
    ; Check if already registered
    push r12
    push r13
    mov r12, rsi
    mov r13, rcx
    xor rax, rax
.search:
    cmp rax, [var_count]
    jge .new
    mov rdi, [var_ptrs + rax * 8]
    mov rdx, [var_lens + rax * 8]
    cmp rdx, r13
    jne .next
    push rax
    push rcx
    mov rsi, r12
    mov rcx, r13
.cmp:
    cmp rcx, 0
    je .found
    movzx edx, byte [rdi]
    cmp dl, [rsi]
    jne .nope
    inc rdi
    inc rsi
    dec rcx
    jmp .cmp
.found:
    pop rcx
    pop rax
    pop r13
    pop r12
    ret
.nope:
    pop rcx
    pop rax
.next:
    inc rax
    jmp .search

.new:
    mov rax, [var_count]
    mov [var_ptrs + rax * 8], r12
    mov [var_lens + rax * 8], r13
    mov byte [var_types + rax], TYPE_INT

    ; Emit to BSS: _v_NAME resq 1
    push rax
    mov rdi, frag_var_pfx
    call bss_str
    mov rsi, r12
    mov rcx, r13
    call bss_n
    mov rdi, frag_resq
    call bss_str
    pop rax

    inc qword [var_count]
    pop r13
    pop r12
    ret

; ============================================================
; out_var_name — Emit "_v_NAME" to output buffer
; rsi = name, rcx = length
; ============================================================
out_var_name:
    push rcx
    push rsi
    mov rdi, frag_var_pfx + 4  ; just "_v_" without leading spaces
    call out_str
    pop rsi
    pop rcx
    call out_n
    ret

; ============================================================
; out_str_id — Emit "_sNN" to output buffer (rdi = id)
; ============================================================
out_str_id:
    push rdi
    mov rdi, frag_s_pfx
    call out_str
    pop rdi
    call out_int
    ret

; out_str_len_id — Emit "_sNN_len" to output buffer (rdi = id)
out_str_len_id:
    push rdi
    mov rdi, frag_s_pfx
    call out_str
    pop rdi
    push rdi
    call out_int
    mov rdi, frag_len_sfx_nl
    call out_str
    pop rdi
    ret

; out_func_name — Emit "_f_NAME" to output buffer
; rsi = name pointer, rcx = name length
out_func_name:
    push rcx
    push rsi
    mov rdi, frag_f_pfx
    call out_str
    pop rsi
    pop rcx
    call out_n
    ret

; ============================================================
; codegen_program — Main entry: generate from token stream
; ============================================================
global codegen_program
codegen_program:
    push rbp
    mov rbp, rsp
    push r12
    push r13
    push r14
    push r15

    mov qword [cg_pos], 0

    ; First pass: scan for string literals and variable names
    ; (We'll register them on-the-fly instead)

    ; Emit header to output
    mov rdi, frag_header
    call out_str
    mov rdi, frag_extern
    call out_str

    ; Emit .text section + _start
    mov rdi, frag_sect_text
    call out_str
    mov rdi, frag_start
    call out_str

    ; Skip mode declaration if present
    call cg_skip_nl
    extern kw_mode
    lea rdi, [kw_mode]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    jne .no_mode
    call cg_advance          ; skip 'mode'
    call cg_advance          ; skip 'hybrid'/'natural'
.no_mode:

    ; Generate code for each statement
.stmt_loop:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .done

    call codegen_stmt
    jmp .stmt_loop

.done:
    ; Emit exit
    mov rdi, frag_exit
    call out_str

    ; Now emit data section
    call out_str_newline
    mov rdi, frag_sect_data
    call out_str
    ; Add newline char constant
    mov rdi, frag_nl_data
    call out_str
    ; Copy data_buf to output
    mov rsi, data_buf
    mov rcx, [data_pos]
    call out_n

    ; Emit BSS section
    mov rdi, frag_sect_bss
    call out_str
    mov rdi, frag_err_resq
    call out_str
    cmp qword [var_count], 0
    je .no_bss
    mov rsi, bss_buf
    mov rcx, [bss_pos]
    call out_n
.no_bss:

    pop r15
    pop r14
    pop r13
    pop r12
    pop rbp
    ret

out_str_newline:
    mov rdi, frag_newline
    call out_str
    ret

; ============================================================
; codegen_stmt — Generate one statement from current position
; ============================================================
codegen_stmt:
    push rbp
    mov rbp, rsp

    call cg_skip_nl
    call cg_tok_type

    ; Keyword dispatch
    cmp al, TOK_KEYWORD
    je .kw_dispatch

    ; Identifier — could be assignment or expression
    cmp al, TOK_IDENT
    je .ident_stmt

    ; Skip other tokens
    call cg_advance
    pop rbp
    ret

.kw_dispatch:
    ; Check each keyword
    extern kw_show
    lea rdi, [kw_show]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_show

    extern kw_err
    lea rdi, [kw_err]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .do_err

    extern kw_if
    lea rdi, [kw_if]
    mov rsi, 2
    call cg_is_kw
    cmp rax, 1
    je .do_if

    extern kw_repeat
    lea rdi, [kw_repeat]
    mov rsi, 6
    call cg_is_kw
    cmp rax, 1
    je .do_repeat

    extern kw_while
    lea rdi, [kw_while]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .do_while

    extern kw_each
    lea rdi, [kw_each]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_each

    extern kw_func
    lea rdi, [kw_func]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_func

    extern kw_return
    lea rdi, [kw_return]
    mov rsi, 6
    call cg_is_kw
    cmp rax, 1
    je .do_return

    extern kw_end
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .do_end

    extern kw_skip
    lea rdi, [kw_skip]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_skip

    extern kw_stop
    lea rdi, [kw_stop]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_stop

    extern kw_error
    lea rdi, [kw_error]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .do_error_kw

    extern kw_try
    lea rdi, [kw_try]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .do_try

    extern kw_push
    lea rdi, [kw_push]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_push_stmt

    extern kw_match
    lea rdi, [kw_match]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .do_match

    extern kw_write
    lea rdi, [kw_write]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .do_write_file

    ; Unknown keyword — report error with line number
    mov rdi, cg_err_unknown_kw
    call cg_error

; ---- show ----
.do_show:
    call cg_advance          ; consume 'show'

    ; Check for .raw
    call cg_tok_type
    cmp al, TOK_DOT
    jne .show_normal
    call cg_advance          ; consume '.'
    call cg_advance          ; consume 'raw'
    call codegen_show_expr
    ; No newline for show.raw
    pop rbp
    ret

.show_normal:
    call codegen_show_expr
    ; Print newline
    mov rdi, frag_print_nl
    call out_str
    pop rbp
    ret

; ---- err ----
.do_err:
    call cg_advance          ; consume 'err'
    ; TODO: stderr variant (for now same as show)
    call codegen_show_expr
    mov rdi, frag_print_nl
    call out_str
    pop rbp
    ret

; ---- if ----
.do_if:
    call cg_advance          ; consume 'if'
    call new_label
    push rax                 ; end_label

    ; Generate condition
    call codegen_expr
    ; Result in rax on stack, pop and test
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_0
    call out_str
    ; je .Lelse
    call new_label
    push rax                 ; else_label
    mov rdi, frag_je
    call out_str
    pop rax
    push rax
    mov rdi, rax
    call out_label_ref
    call out_str_newline

    ; Generate body until end/elif/else
.if_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .if_done

    extern kw_end
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .if_end

    extern kw_elif
    lea rdi, [kw_elif]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .if_elif

    ; "or if" — child-friendly alias for elif
    ; Consume 'or', skip newlines, then treat as elif (next token must be 'if')
    extern kw_or
    lea rdi, [kw_or]
    mov rsi, 2
    call cg_is_kw
    cmp rax, 1
    jne .not_or_if
    call cg_advance          ; consume 'or'
    call cg_skip_nl
    ; now current token should be 'if' — .if_elif will cg_advance it as 'elif'
    jmp .if_elif
.not_or_if:

    extern kw_else
    lea rdi, [kw_else]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .if_else

    call codegen_stmt
    jmp .if_body

.if_elif:
    ; Jump to end
    pop rax                  ; else_label
    push rax
    mov rdi, frag_jmp
    call out_str
    mov rdi, [rsp + 8]      ; end_label
    call out_label_ref
    call out_str_newline
    ; Emit else label
    pop rdi
    call out_label_def
    ; Process elif as new if
    call cg_advance          ; consume 'elif'
    call codegen_expr
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_0
    call out_str
    call new_label
    push rax
    mov rdi, frag_je
    call out_str
    pop rax
    push rax
    mov rdi, rax
    call out_label_ref
    call out_str_newline
    jmp .if_body

.if_else:
    ; Jump to end
    mov rdi, frag_jmp
    call out_str
    mov rdi, [rsp + 8]      ; end_label
    call out_label_ref
    call out_str_newline
    ; Emit else label
    pop rdi
    call out_label_def
    call cg_advance          ; consume 'else'
    ; Generate else body
    call new_label
    push rax                 ; dummy else label (not used)
    jmp .if_body

.if_end:
    call cg_advance          ; consume 'end'
    ; Emit both labels (else points here too)
    pop rdi                  ; else_label
    call out_label_def
.if_done:
    pop rdi                  ; end_label
    call out_label_def
    pop rbp
    ret

; ---- repeat ----
.do_repeat:
    call cg_advance          ; consume 'repeat'

    ; Parse count expression
    call codegen_expr
    ; Count is on stack

    ; Check for 'times' keyword (optional)
    extern kw_times
    lea rdi, [kw_times]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    jne .no_times
    call cg_advance
.no_times:

    ; Check for 'as' (loop variable)
    extern kw_as
    lea rdi, [kw_as]
    mov rsi, 2
    call cg_is_kw
    cmp rax, 1
    jne .no_loop_var

    call cg_advance          ; consume 'as'
    call cg_peek
    mov rsi, [rax + 8]      ; var name
    mov ecx, [rax + 4]      ; var name length
    call register_var        ; register loop var
    call cg_advance          ; consume var name

    ; Initialize loop var to 0: mov qword [_v_i], 0
    mov rdi, frag_movq_bracket
    call out_str
    ; Get the var we just registered
    mov rax, [var_count]
    dec rax
    mov r14, rax             ; save var index for increment later
    mov rsi, [var_ptrs + rax * 8]
    mov rcx, [var_lens + rax * 8]
    call out_var_name
    mov rdi, frag_close_comma_0
    call out_str
    jmp .repeat_loop_start

.no_loop_var:
    mov r14, -1              ; no loop variable

.repeat_loop_start:
    ; Pop count into rcx
    mov rdi, frag_pop_rcx2
    call out_str

    ; Labels
    call new_label
    mov r12, rax             ; top label
    call new_label
    mov r13, rax             ; end label

    ; Push to loop stack
    mov rax, [loop_depth]
    mov [loop_top + rax * 8], r12
    mov [loop_end + rax * 8], r13
    inc qword [loop_depth]

    ; Save count: push rcx
    mov rdi, frag_push_rcx
    call out_str

    ; Top label
    mov rdi, r12
    call out_label_def

    ; Check count > 0: pop rcx, cmp rcx, 0, jle end
    mov rdi, frag_pop_rcx2
    call out_str
    ; cmp rcx, 0
    mov rdi, frag_cmp_rcx_0
    call out_str
    ; Push counter back for stack balance (exit path + body both expect it)
    mov rdi, frag_push_rcx
    call out_str

    ; jle end
    mov rdi, frag_jle
    call out_str
    mov rdi, r13
    call out_label_ref
    call out_str_newline

    ; Generate body
.repeat_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .repeat_end_eof

    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .repeat_end

    push r12
    push r13
    push r14
    call codegen_stmt
    pop r14
    pop r13
    pop r12
    jmp .repeat_body

.repeat_end:
    call cg_advance          ; consume 'end'
.repeat_end_eof:

    ; Increment loop var if exists, dec count, jump to top
    cmp r14, -1
    je .repeat_no_inc
    ; inc qword [_v_NAME]
    mov rdi, frag_inc_qword_bracket
    call out_str
    mov rax, r14
    mov rsi, [var_ptrs + rax * 8]
    mov rcx, [var_lens + rax * 8]
    call out_var_name
    mov rdi, frag_close
    call out_str
.repeat_no_inc:

    ; Decrement: pop rcx, dec rcx, push rcx, jmp top
    mov rdi, frag_pop_rcx2
    call out_str
    mov rdi, frag_dec_rcx
    call out_str
    mov rdi, frag_push_rcx
    call out_str
    mov rdi, frag_jmp
    call out_str
    mov rdi, r12
    call out_label_ref
    call out_str_newline

    ; End label (cleanup: pop rcx off stack)
    mov rdi, r13
    call out_label_def
    mov rdi, frag_pop_rcx2
    call out_str

    ; Pop loop stack
    dec qword [loop_depth]

    pop rbp
    ret

; ---- while ----
; ---- each ARRAY as VAR ... end ----
.do_each:
    call cg_advance          ; consume 'each'

    ; Evaluate array expression
    call codegen_expr         ; push array ptr

    ; Expect 'as'
    call cg_advance          ; consume 'as'

    ; Get first variable name (could be value var, or index var if comma follows)
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    call register_var
    mov r14, rax             ; save first var index
    call cg_advance          ; consume var name

    ; Check for comma (index, value syntax)
    mov r15, -1              ; r15 = index var (-1 = none)
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .each_no_index
    call cg_tok_sub
    cmp al, PUNCT_COMMA
    jne .each_no_index
    call cg_advance          ; consume ','
    ; First var was the index var, now read value var
    mov r15, r14             ; r15 = index var index
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    call register_var
    mov r14, rax             ; r14 = value var index
    call cg_advance          ; consume value var name
.each_no_index:

    ; Labels
    call new_label
    mov r12, rax             ; top label
    call new_label
    mov r13, rax             ; end label

    ; Emit: pop rdi (array) / push rdi / push 0 (index)
    mov rdi, frag_pop_rdi
    call out_str
    mov rdi, frag_push_rdi
    call out_str
    mov rdi, frag_xor_rax
    call out_str
    mov rdi, frag_push_rax
    call out_str

    ; Top label
    mov rdi, r12
    call out_label_def

    ; Check index < arr_len
    mov rdi, frag_each_check
    call out_str
    mov rdi, frag_jge
    call out_str
    mov rdi, r13
    call out_label_ref
    call out_str_newline

    ; Get element: arr[index]
    mov rdi, frag_each_get_elem
    call out_str
    ; Store element in value variable
    mov rdi, frag_mov_bracket
    call out_str
    mov rax, r14
    mov rsi, [var_ptrs + rax * 8]
    mov rcx, [var_lens + rax * 8]
    call out_var_name
    mov rdi, frag_close_rax
    call out_str

    ; If index variable exists, store current index in it
    cmp r15, -1
    je .each_skip_store_idx
    ; The index is on stack: pop rax (index), pop rdi (array), push rdi, push rax
    ; After frag_each_get_elem, stack is: [array, index] with index on top
    ; We need to read the index. It's at [rsp] (top of stack).
    ; Emit: mov rax, [rsp]  — peek at index without popping
    mov rdi, frag_mov_rax_rsp
    call out_str
    ; Emit: mov [_v_IDX], rax
    mov rdi, frag_mov_bracket
    call out_str
    mov rax, r15
    mov rsi, [var_ptrs + rax * 8]
    mov rcx, [var_lens + rax * 8]
    call out_var_name
    mov rdi, frag_close_rax
    call out_str
.each_skip_store_idx:

    ; Generate body
.each_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .each_end_eof

    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .each_end

    push r12
    push r13
    push r14
    push r15
    call codegen_stmt
    pop r15
    pop r14
    pop r13
    pop r12
    jmp .each_body

.each_end:
    call cg_advance          ; consume 'end'
.each_end_eof:
    ; Increment index: pop rax (index), inc, pop rdi (array), push rdi, push rax, jmp top
    mov rdi, frag_each_inc
    call out_str
    mov rdi, frag_jmp
    call out_str
    mov rdi, r12
    call out_label_ref
    call out_str_newline

    ; End label — cleanup stack (pop index, pop array)
    mov rdi, r13
    call out_label_def
    mov rdi, frag_each_cleanup
    call out_str

    pop rbp
    ret

; ---- while ----
.do_while:
    call cg_advance          ; consume 'while'

    call new_label
    mov r12, rax             ; top label
    call new_label
    mov r13, rax             ; end label

    ; Push to loop stack
    mov rax, [loop_depth]
    mov [loop_top + rax * 8], r12
    mov [loop_end + rax * 8], r13
    inc qword [loop_depth]

    ; Top label
    mov rdi, r12
    call out_label_def

    ; Condition
    call codegen_expr
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_0
    call out_str
    mov rdi, frag_je
    call out_str
    mov rdi, r13
    call out_label_ref
    call out_str_newline

    ; Body
.while_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .while_end_eof

    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .while_end

    push r12
    push r13
    push r14
    call codegen_stmt
    pop r14
    pop r13
    pop r12
    jmp .while_body

.while_end:
    call cg_advance
.while_end_eof:
    mov rdi, frag_jmp
    call out_str
    mov rdi, r12
    call out_label_ref
    call out_str_newline
    mov rdi, r13
    call out_label_def
    dec qword [loop_depth]
    pop rbp
    ret

; ---- func ----
.do_func:
    call cg_advance          ; consume 'func'

    ; Jump over function body in main flow
    call new_label
    mov r14, rax
    mov rdi, frag_jmp
    call out_str
    mov rdi, r14
    call out_label_ref
    call out_str_newline

    ; Function name
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    push rcx
    push rsi

    ; Emit label: _f_name:
    pop rsi
    pop rcx
    push rcx
    push rsi
    call out_func_name
    mov rdi, frag_colon
    call out_str

    call cg_advance          ; consume name

    ; Prologue
    mov rdi, frag_func_pro
    call out_str

    ; Parse '(' params ')' and store from registers
    mov qword [cur_params], 0
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .func_no_parens
    call cg_tok_sub
    cmp al, PUNCT_LPAREN
    jne .func_no_parens
    call cg_advance          ; consume '('
.parse_params:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .param_ident
    call cg_tok_sub
    cmp al, PUNCT_RPAREN
    je .params_done
    cmp al, PUNCT_COMMA
    jne .params_done
    call cg_advance          ; consume ','
    jmp .parse_params
.param_ident:
    ; Check for 'many' keyword (variadic)
    cmp al, TOK_KEYWORD
    jne .not_many_kw
    extern kw_many
    lea rdi, [kw_many]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    jne .not_many_kw
    call cg_advance          ; consume 'many'
    jmp .do_many_param
.not_many_kw:

    cmp al, TOK_IDENT
    jne .params_done
    ; Register this param as a variable
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    push rcx
    push rsi
    call register_var
    call cg_advance

    ; Check for default value: = VALUE
    xor r15, r15             ; r15 = 0 (no default), 1 = int, 2 = string
    call cg_tok_type
    cmp al, TOK_OP
    jne .no_default
    call cg_tok_sub
    cmp al, OP_ASSIGN
    jne .no_default
    call cg_advance          ; consume '='
    ; Check default value token type
    call cg_tok_type
    cmp al, TOK_STRING
    je .default_string
    ; Integer default
    call cg_peek
    mov r12, [rax + 8]       ; r12 = default value ptr
    mov r13d, [rax + 4]      ; r13 = default value len
    mov r15, 1               ; int default
    call cg_advance
    jmp .no_default
.default_string:
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    call register_string
    mov r12, rax             ; r12 = string ID
    mov r15, 2               ; string default
    call cg_advance
.no_default:

    pop rsi
    pop rcx

    ; Emit: mov [_v_PARAM], REG  (register from arg_reg_table)
    push rcx
    push rsi
    mov rdi, frag_mov_bracket
    call out_str
    pop rsi
    pop rcx
    push rcx
    push rsi
    call out_var_name
    mov rdi, frag_close_reg
    call out_str
    ; Get register name for this param index
    mov rax, [cur_params]
    cmp rax, 6
    jge .param_skip_reg
    mov rdi, [arg_reg_table + rax * 8]
    call out_str
    call out_str_newline
.param_skip_reg:

    ; If has default value, emit conditional: if param==0, set default
    ; Stack: [rsi (name ptr), rcx (name len)]
    ; r12 = default value ptr, r13 = default value len, r15 = has default flag
    cmp r15, 0
    je .no_default_emit

    ; Get a label for the skip target
    call new_label
    push rax                 ; save label number (stack: [label, rsi, rcx])

    ; Emit: cmp qword [_v_PARAM], 0
    mov rdi, frag_cmp_qword
    call out_str
    mov rsi, [rsp + 8]      ; param name ptr
    mov ecx, [rsp + 16]     ; param name len
    call out_var_name
    mov rdi, frag_close_0
    call out_str

    ; Emit: jne _LN
    mov rdi, frag_jne
    call out_str
    mov rdi, [rsp]           ; label number
    call out_label_ref
    call out_str_newline

    ; Emit: mov qword [_v_PARAM], DEFAULT
    mov rdi, frag_mov_qword
    call out_str
    mov rsi, [rsp + 8]      ; param name ptr
    mov ecx, [rsp + 16]     ; param name len
    call out_var_name
    mov rdi, frag_close_comma
    call out_str
    cmp r15, 2
    je .default_emit_str
    ; Integer default
    mov rsi, r12             ; default value text ptr
    mov ecx, r13d            ; default value text len
    call out_n
    call out_str_newline
    jmp .default_emit_done
.default_emit_str:
    ; String default: emit _sN
    mov rdi, r12             ; string ID
    call out_str_id
    call out_str_newline
.default_emit_done:

    ; Emit: _LN:
    pop rdi                  ; label number
    call out_label_def
.no_default_emit:

    pop rsi
    pop rcx
    inc qword [cur_params]
    jmp .parse_params
.do_many_param:
    ; 'many' consumed, now read the variadic param name
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    push rcx
    push rsi
    call register_var
    call cg_advance          ; consume param name

    ; Unrolled variadic: save arg regs, create array, push each in range
    ; Generated code uses r12=arg count, r13=array ptr (callee-saved)
    ; After push rbp/mov rbp,rsp, args land at:
    ;   [rbp-8]=rdi, [rbp-16]=rsi, [rbp-24]=rdx,
    ;   [rbp-32]=rcx, [rbp-40]=r8, [rbp-48]=r9
    mov rdi, frag_push_rdi
    call out_str
    mov rdi, frag_push_rsi
    call out_str
    mov rdi, frag_push_rdx
    call out_str
    mov rdi, frag_push_rcx
    call out_str
    mov rdi, frag_push_r8
    call out_str
    mov rdi, frag_push_r9
    call out_str

    ; Emit: mov r12, r10 (save arg count before calls)
    mov rdi, frag_mov_r12_r10
    call out_str
    ; Emit: xor rdi, rdi / call rt_arr_new / mov r13, rax
    mov rdi, frag_xor_rdi
    call out_str
    mov rdi, frag_call_arr_new_no_push
    call out_str
    mov rdi, frag_mov_r13_rax
    call out_str

    ; Get done label
    push r14                 ; save function skip label
    call new_label
    push rax                 ; save done label on codegen stack

    ; Unroll: for each arg slot from cur_params to 5
    ; Emit: cmp r12, N+1 / jl done / mov rdi, r13 / mov rsi, [rbp-offset] / call rt_arr_push / mov r13, rax
    mov r14, [cur_params]    ; start index
.many_unroll:
    cmp r14, 6
    jge .many_unroll_done

    ; Emit: cmp r12, INDEX+1
    mov rdi, frag_cmp_r12
    call out_str
    mov rdi, r14
    inc rdi
    call out_int
    call out_str_newline

    ; Emit: jl done_label
    mov rdi, frag_jl
    call out_str
    mov rdi, [rsp]           ; done label from codegen stack
    call out_label_ref
    call out_str_newline

    ; Emit: mov rdi, r13 / mov rsi, [rbp - OFFSET]
    mov rdi, frag_mov_rdi_r13
    call out_str
    mov rdi, frag_mov_rsi_rbp
    call out_str
    mov rax, r14
    inc rax
    shl rax, 3               ; (index+1) * 8
    mov rdi, rax
    call out_int
    mov rdi, frag_close
    call out_str

    ; Emit: call rt_arr_push / mov r13, rax
    mov rdi, frag_call_arr_push
    call out_str
    mov rdi, frag_mov_r13_rax
    call out_str

    inc r14
    jmp .many_unroll
.many_unroll_done:
    ; Stack: [bottom] var_rcx, var_rsi, r14_saved, done_label [top]
    pop rdi                  ; done label
    call out_label_def
    pop r14                  ; restore function skip label
    ; Stack: [bottom] var_rcx, var_rsi [top]
    pop rsi
    pop rcx
    push rcx
    push rsi
    mov rdi, frag_mov_bracket
    call out_str
    call out_var_name
    mov rdi, frag_close_r13
    call out_str
    mov rdi, frag_add_rsp_48
    call out_str

    pop rsi
    pop rcx
    ; Skip to params_done (many must be last param)
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .params_done
    call cg_tok_sub
    cmp al, PUNCT_RPAREN
    je .params_done
    jmp .params_done

.params_done:
    call cg_advance          ; consume ')'
.func_no_parens:

    ; Generate body
.func_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .func_end_eof

    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .func_end

    push r12
    push r13
    push r14
    call codegen_stmt
    pop r14
    pop r13
    pop r12
    jmp .func_body

.func_end:
    call cg_advance
.func_end_eof:
    ; Epilogue (default return 0)
    mov rdi, frag_xor_rax
    call out_str
    mov rdi, frag_func_epi
    call out_str

    ; After-function label
    mov rdi, r14
    call out_label_def

    pop rsi
    pop rcx
    pop rbp
    ret

; ---- return ----
.do_return:
    call cg_advance          ; consume 'return'
    call cg_tok_type
    cmp al, TOK_NEWLINE
    je .empty_return
    cmp al, TOK_EOF
    je .empty_return
    call codegen_expr
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_func_epi
    call out_str
    pop rbp
    ret
.empty_return:
    mov rdi, frag_xor_rax
    call out_str
    mov rdi, frag_func_epi
    call out_str
    pop rbp
    ret

; ---- end ---- (stray end — should have been consumed by block)
.do_end:
    call cg_advance
    pop rbp
    ret

; ---- skip (continue) ----
.do_skip:
    call cg_advance
    mov rax, [loop_depth]
    cmp rax, 0
    je .skip_noop
    dec rax
    mov rdi, [loop_top + rax * 8]
    push rdi
    mov rdi, frag_jmp
    call out_str
    pop rdi
    call out_label_ref
    call out_str_newline
.skip_noop:
    pop rbp
    ret

; ---- stop (break) ----
.do_stop:
    call cg_advance
    mov rax, [loop_depth]
    cmp rax, 0
    je .stop_noop
    dec rax
    mov rdi, [loop_end + rax * 8]
    push rdi
    mov rdi, frag_jmp
    call out_str
    pop rdi
    call out_label_ref
    call out_str_newline
.stop_noop:
    pop rbp
    ret

; ---- error ----
.do_error_kw:
    call cg_advance          ; consume 'error'
    ; Evaluate the error message expression
    call codegen_expr
    ; If inside try/catch, jump to catch handler
    mov rax, [try_depth]
    cmp rax, 0
    je .error_no_try
    ; Pop error value into _v___err, jump to catch
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_mov_err_rax
    call out_str
    dec rax
    mov rdi, frag_jmp
    call out_str
    mov rax, [try_depth]
    dec rax
    mov rdi, [try_catch + rax * 8]
    call out_label_ref
    call out_str_newline
    pop rbp
    ret
.error_no_try:
    ; Outside try: exit with code 1
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_exit1
    call out_str
    pop rbp
    ret

; ---- try/catch/end ----
.do_try:
    call cg_advance          ; consume 'try'
    ; Allocate labels
    call new_label
    mov r12, rax             ; catch label
    call new_label
    mov r13, rax             ; end label
    ; Push to try stack
    mov rax, [try_depth]
    mov [try_catch + rax * 8], r12
    mov [try_end + rax * 8], r13
    inc qword [try_depth]
    ; Try body: loop until 'catch' or 'end'
.try_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .try_done
    extern kw_catch
    lea rdi, [kw_catch]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .try_catch_found
    extern kw_end
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .try_end_no_catch
    push r12
    push r13
    call codegen_stmt
    pop r13
    pop r12
    jmp .try_body
.try_catch_found:
    ; End of try body — jump to end (no error path)
    mov rdi, frag_jmp
    call out_str
    mov rdi, r13
    call out_label_ref
    call out_str_newline
    ; Emit catch label
    mov rdi, r12
    call out_label_def
    call cg_advance          ; consume 'catch'
    ; Read error variable name (optional)
    call cg_tok_type
    cmp al, TOK_IDENT
    jne .catch_no_var
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    push rcx
    push rsi
    call register_var
    ; Emit: mov rax, [__err] / mov [_v_e], rax
    mov rdi, frag_mov_rax_err
    call out_str
    mov rdi, frag_mov_bracket
    call out_str
    pop rsi
    pop rcx
    call out_var_name
    mov rdi, frag_close_rax
    call out_str
    call cg_advance          ; consume var name
.catch_no_var:
    ; Catch body
.catch_body:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .try_done
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .try_done
    push r13
    call codegen_stmt
    pop r13
    jmp .catch_body
.try_end_no_catch:
    ; try without catch — just close it
.try_done:
    call cg_advance          ; consume 'end'
    dec qword [try_depth]
    ; Emit end label
    mov rdi, r13
    call out_label_def
    pop rbp
    ret

; ---- push(arr, val) statement ----
.do_push_stmt:
    call cg_advance          ; consume 'push'
    call cg_advance          ; consume '('
    ; Read array variable name
    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    push rcx
    push rsi
    call cg_advance          ; consume array name
    call cg_advance          ; consume ','
    ; Evaluate value expression → pushed on stack
    call codegen_expr
    ; Emit: pop rsi / mov rdi, [_v_ARR] / call rt_arr_push / mov [_v_ARR], rax
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_mov_rdi_bracket
    call out_str
    pop rsi
    pop rcx
    push rcx
    push rsi
    call out_var_name
    mov rdi, frag_close
    call out_str
    mov rdi, frag_call_arr_push
    call out_str
    mov rdi, frag_mov_bracket
    call out_str
    pop rsi
    pop rcx
    call out_var_name
    mov rdi, frag_close_rax
    call out_str
    ; Consume ')'
    call cg_advance
    pop rbp
    ret

; ---- identifier statement (assignment or expression) ----
.ident_stmt:
    ; Save current pos to check for assignment
    call cg_peek
    mov r12, [rax + 8]      ; ident text
    mov r13d, [rax + 4]     ; ident length
    call cg_advance          ; consume ident

    ; Check for '=' (assignment)
    call cg_tok_type
    cmp al, TOK_OP
    jne .ident_expr
    call cg_tok_sub
    cmp al, OP_ASSIGN
    jne .ident_expr

    call cg_advance          ; consume '='

    ; Check for ask/secret
    extern kw_ask
    lea rdi, [kw_ask]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    je .do_assign_ask

    extern kw_secret
    lea rdi, [kw_secret]
    mov rsi, 6
    call cg_is_kw
    cmp rax, 1
    je .do_assign_ask

    extern kw_read
    lea rdi, [kw_read]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_assign_read

    ; Regular assignment: var = expr
    mov rsi, r12
    movzx rcx, r13d
    call register_var

    call codegen_expr
    mov rdi, frag_pop_rax
    call out_str

    ; mov [_v_name], rax
    mov rdi, frag_mov_bracket
    call out_str
    mov rsi, r12
    movzx rcx, r13d
    call out_var_name
    mov rdi, frag_close_rax
    call out_str

    pop rbp
    ret

; ---- match / case / else / end ----
.do_match:
    call cg_advance          ; consume 'match'
    call cg_skip_nl

    ; Evaluate the match expression → on stack
    call codegen_expr

    ; r12 = end label
    call new_label
    mov r12, rax

    call cg_skip_nl

.match_case_loop:
    call cg_skip_nl
    call cg_tok_type
    cmp al, TOK_EOF
    je .match_done
    cmp al, TOK_KEYWORD
    jne .match_done

    ; Check for 'case'
    push r12
    extern kw_case
    lea rdi, [kw_case]
    mov rsi, 4
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_case

    ; Check for 'else'
    push r12
    extern kw_else
    lea rdi, [kw_else]
    mov rsi, 4
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_else

    ; Check for 'end'
    push r12
    extern kw_end
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_end

    jmp .match_done

.match_case:
    call cg_advance          ; consume 'case'
    call cg_skip_nl

    ; Get labels for this case
    call new_label
    push rax                 ; body_label
    call new_label
    push rax                 ; next_label

    ; Duplicate match value: mov rax, [rsp+16] (skip 2 pushed labels)
    ; Actually the match value is on the asm runtime stack, not here.
    ; emit: mov rax, [rsp] / push rax  — copies top of runtime stack
    mov rdi, frag_mov_rax_rsp
    call out_str
    mov rdi, frag_push_rax
    call out_str

    ; Evaluate case value expression
    call codegen_expr

    ; pop rbx (case val), pop rax (match val copy)
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str

    ; Integer compare: cmp rax, rbx / je body
    mov rdi, frag_cmp_rax_rbx2
    call out_str
    mov rdi, frag_je
    call out_str
    mov rdi, [rsp + 8]      ; body_label
    call out_label_ref
    call out_str_newline

    ; String compare fallback: save regs, call rt_str_eq, check
    mov rdi, frag_push_rax
    call out_str
    mov rdi, frag_push_rbx
    call out_str
    mov rdi, frag_mov_rdi_from_rax
    call out_str
    mov rdi, frag_mov_rsi_from_rbx
    call out_str
    mov rdi, frag_call_str_eq
    call out_str
    mov rdi, frag_cmp_rax_1
    call out_str
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_je
    call out_str
    mov rdi, [rsp + 8]      ; body_label
    call out_label_ref
    call out_str_newline

    ; jmp next_label
    mov rdi, frag_jmp
    call out_str
    mov rdi, [rsp]           ; next_label
    call out_label_ref
    call out_str_newline

    ; body_label:
    mov rdi, [rsp + 8]
    call out_label_def

    ; Execute body statements until next case/else/end
    call cg_skip_nl
.match_body_loop:
    call cg_tok_type
    cmp al, TOK_EOF
    je .match_case_body_end
    cmp al, TOK_KEYWORD
    jne .match_body_stmt

    push r12
    extern kw_case
    lea rdi, [kw_case]
    mov rsi, 4
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_case_body_end

    push r12
    extern kw_else
    lea rdi, [kw_else]
    mov rsi, 4
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_case_body_end

    push r12
    extern kw_end
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_case_body_end

.match_body_stmt:
    push r12
    call codegen_stmt
    pop r12
    call cg_skip_nl
    jmp .match_body_loop

.match_case_body_end:
    ; Jump to match end
    mov rdi, frag_jmp
    call out_str
    mov rdi, r12             ; end label
    call out_label_ref
    call out_str_newline

    ; next_label:
    pop rdi                  ; next_label
    call out_label_def
    pop rax                  ; body_label (discard)

    jmp .match_case_loop

.match_else:
    call cg_advance          ; consume 'else'
    call cg_skip_nl
.match_else_loop:
    call cg_tok_type
    cmp al, TOK_EOF
    je .match_done
    cmp al, TOK_KEYWORD
    jne .match_else_stmt

    push r12
    extern kw_end
    lea rdi, [kw_end]
    mov rsi, 3
    call cg_is_kw
    pop r12
    cmp rax, 1
    je .match_end

.match_else_stmt:
    push r12
    call codegen_stmt
    pop r12
    call cg_skip_nl
    jmp .match_else_loop

.match_end:
    call cg_advance          ; consume 'end'
.match_done:
    ; Pop match value from stack
    mov rdi, frag_pop_rax
    call out_str
    ; End label
    mov rdi, r12
    call out_label_def
    pop rbp
    ret

; ---- write "filename", data ----
.do_write_file:
    call cg_advance          ; consume 'write'
    call cg_skip_nl
    ; Evaluate filename expression
    call codegen_expr
    ; Skip comma
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .write_no_comma
    call cg_tok_sub
    cmp al, PUNCT_COMMA
    jne .write_no_comma
    call cg_advance          ; consume ','
.write_no_comma:
    call cg_skip_nl
    ; Evaluate data expression
    call codegen_expr
    ; Stack: [filename_ptr, data_ptr]
    ; pop rsi (data), pop rdi (filename)
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_pop_rdi
    call out_str
    mov rdi, frag_call_file_write
    call out_str
    pop rbp
    ret

.do_assign_ask:
    call cg_advance          ; consume 'ask'/'secret'

    ; Register variable
    mov rsi, r12
    movzx rcx, r13d
    call register_var

    ; Get prompt string
    call cg_peek
    movzx eax, byte [rax]
    cmp al, TOK_STRING
    jne .ask_no_prompt

    call cg_peek
    mov rsi, [rax + 8]
    mov ecx, [rax + 4]
    call register_string
    push rax                 ; string ID
    call cg_advance

    ; Emit: mov rsi, _sNN / mov rdx, _sNN_len / call rt_prompt
    mov rdi, frag_mov_rsi
    call out_str
    pop rax
    push rax
    mov rdi, rax
    call out_str_id
    call out_str_newline

    mov rdi, frag_mov_rdx
    call out_str
    pop rax
    mov rdi, rax
    call out_str_len_id
    call out_str_newline

    mov rdi, frag_prompt
    call out_str
    jmp .ask_store

.ask_no_prompt:
    mov rdi, frag_read_line
    call out_str

.ask_store:
    ; rax has pointer to input, try to convert to int
    mov rdi, frag_mov_rax_rsi
    call out_str
    mov rdi, frag_str2int
    call out_str

    ; Store result: mov [_v_name], rax
    mov rdi, frag_mov_bracket
    call out_str
    mov rsi, r12
    movzx rcx, r13d
    call out_var_name
    mov rdi, frag_close_rax
    call out_str

    pop rbp
    ret

.do_assign_read:
    call cg_advance          ; consume 'read'

    ; Register variable
    mov rsi, r12
    movzx rcx, r13d
    call register_var

    ; Evaluate filename expression
    push r12
    push r13
    call codegen_expr
    pop r13
    pop r12

    ; pop rdi (filename) / call rt_file_read_str
    mov rdi, frag_pop_rdi
    call out_str
    mov rdi, frag_call_file_read
    call out_str

    ; Store result: mov [_v_name], rax
    mov rdi, frag_mov_bracket
    call out_str
    mov rsi, r12
    movzx rcx, r13d
    call out_var_name
    mov rdi, frag_close_rax
    call out_str

    pop rbp
    ret

.ident_expr:
    ; Could be function call — check for '('
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .ident_done
    call cg_tok_sub
    cmp al, PUNCT_LPAREN
    jne .ident_done

    ; Function call as statement
    call cg_advance          ; consume '('
    xor r14, r14             ; arg count
    call codegen_call_args   ; eval args, pop into regs

    ; Emit: call _f_name
    mov rdi, frag_call
    call out_str
    mov rsi, r12
    movzx rcx, r13d
    call out_func_name
    call out_str_newline

.ident_done:
    pop rbp
    ret

; ============================================================
; codegen_show_expr — Generate code to print expression result
; Handles int and string types
; ============================================================
codegen_show_expr:
    push rbp
    mov rbp, rsp

    ; Check if it's a string literal directly (but not if followed by an operator like +)
    call cg_tok_type
    cmp al, TOK_STRING
    jne .show_expr
    ; Peek at next token to see if it's an operator
    inc qword [cg_pos]
    call cg_tok_type
    dec qword [cg_pos]
    cmp al, TOK_OP
    je .show_expr              ; string + something: use full expression path
    jmp .show_string
.show_expr:

    ; Otherwise generate expression and print as val (auto-detect type)
    call codegen_expr
    mov rdi, frag_pop_rdi
    call out_str
    mov rdi, frag_print_val
    call out_str

    ; Check for more comma-separated values
.check_comma:
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .done
    call cg_tok_sub
    cmp al, PUNCT_COMMA
    jne .done
    call cg_advance          ; consume ','
    ; Print space
    mov rdi, frag_print_sp
    call out_str
    ; Print next expression
    call codegen_show_expr
.done:
    pop rbp
    ret

.show_string:
    call cg_peek
    mov rsi, [rax + 8]       ; string content ptr
    mov ecx, [rax + 4]       ; string length
    call cg_advance

    ; Check if string contains '{' for interpolation
    push rsi
    push rcx
    mov rdi, rsi
    mov r8, rcx
.interp_scan:
    cmp r8, 0
    je .no_interp
    cmp byte [rdi], '{'
    je .has_interp
    inc rdi
    dec r8d
    jmp .interp_scan

.no_interp:
    pop rcx
    pop rsi
    ; Simple string — register and print
    call register_string
    mov r15, rax
    mov rdi, frag_mov_rsi
    call out_str
    mov rdi, r15
    call out_str_id
    call out_str_newline
    mov rdi, frag_mov_rdx
    call out_str
    mov rdi, r15
    call out_str_len_id
    call out_str_newline
    mov rdi, frag_print_str
    call out_str
    jmp .check_comma

.has_interp:
    pop rcx
    pop rsi
    ; rsi = start of string, ecx = total length
    ; Walk through segments: text / {var} / text / {var} ...
    push r12
    push r13
    push r14
    push r15
    mov r12, rsi              ; current position
    mov r13, rcx              ; remaining length
.interp_loop:
    cmp r13, 0
    jle .interp_done
    ; Find next '{'
    mov rdi, r12
    mov r8, r13
    mov r14, r12              ; segment start
.find_brace:
    cmp r8, 0
    je .interp_tail
    cmp byte [rdi], '{'
    je .found_brace
    inc rdi
    dec r8
    jmp .find_brace

.interp_tail:
    ; No more '{' — print remaining text
    mov rsi, r14
    mov rcx, r13
    cmp rcx, 0
    je .interp_done
    call register_string
    mov r15, rax
    mov rdi, frag_mov_rsi
    call out_str
    mov rdi, r15
    call out_str_id
    call out_str_newline
    mov rdi, frag_mov_rdx
    call out_str
    mov rdi, r15
    call out_str_len_id
    call out_str_newline
    mov rdi, frag_print_str
    call out_str
    jmp .interp_done

.found_brace:
    ; Print text before '{'
    mov rcx, rdi
    sub rcx, r14              ; length of text segment
    cmp ecx, 0
    je .skip_text_seg
    mov rsi, r14
    push rdi
    push r8
    call register_string
    mov r15, rax
    mov rdi, frag_mov_rsi
    call out_str
    mov rdi, r15
    call out_str_id
    call out_str_newline
    mov rdi, frag_mov_rdx
    call out_str
    mov rdi, r15
    call out_str_len_id
    call out_str_newline
    mov rdi, frag_print_str
    call out_str
    pop r8
    pop rdi
.skip_text_seg:
    ; Skip '{'
    inc rdi
    dec r8
    ; Find closing '}'
    mov r14, rdi              ; var name start
.find_close:
    cmp r8, 0
    je .interp_done           ; unterminated — bail
    cmp byte [rdi], '}'
    je .found_close
    inc rdi
    dec r8
    jmp .find_close
.found_close:
    ; r14 = var name start, rdi = at '}'
    mov rcx, rdi
    sub rcx, r14              ; var name length
    mov rsi, r14
    ; Register the variable (ensure it exists in BSS)
    push rdi
    push r8
    call register_var
    ; register_var returned index in rax
    mov rbx, rax
    ; Emit: mov rax, [_v_NAME]
    mov rdi, frag_mov_rax_bracket
    call out_str
    pop r8
    pop rdi
    push rdi
    push r8
    mov rsi, [var_ptrs + rbx * 8]
    mov rcx, [var_lens + rbx * 8]
    call out_var_name
    mov rdi, frag_close
    call out_str
    ; call rt_print_val — auto-detects string pointer vs integer
    mov rdi, frag_push_rax
    call out_str
    mov rdi, frag_pop_rdi
    call out_str
    mov rdi, frag_print_val
    call out_str
    pop r8
    pop rdi
    ; Skip '}'
    inc rdi
    dec r8
    ; Update position
    mov r12, rdi
    mov r13, r8
    jmp .interp_loop

.interp_done:
    pop r15
    pop r14
    pop r13
    pop r12
    jmp .check_comma

; ============================================================
; codegen_expr — Generate expression, result pushed on stack
; Handles precedence: compare > add > mul > primary
; ============================================================
codegen_expr:
    push rbp
    mov rbp, rsp
    call cg_expr_or
    pop rbp
    ret

cg_expr_or:
    call cg_expr_and
.loop:
    call cg_tok_type
    cmp al, TOK_KEYWORD
    jne .done
    extern kw_or
    lea rdi, [kw_or]
    mov rsi, 2
    call cg_is_kw
    cmp rax, 1
    jne .done
    ; Peek next — if next is 'if', don't consume (it's 'or if' for elif)
    push rbx
    mov rdi, [cg_pos]
    inc rdi
    call lexer_get_token
    movzx ebx, byte [rax]
    cmp bl, TOK_KEYWORD
    jne .is_or_op
    mov ecx, [rax + 4]
    cmp ecx, 2
    jne .is_or_op
    mov rdi, [rax + 8]
    cmp byte [rdi], 'i'
    jne .is_or_op
    cmp byte [rdi+1], 'f'
    jne .is_or_op
    pop rbx
    jmp .done               ; 'or if' = elif, don't consume
.is_or_op:
    pop rbx
    call cg_advance          ; consume 'or'
    call cg_expr_and
    ; pop b, pop a, or => (a != 0) || (b != 0)
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    ; or rax, rbx / test / setne
    mov rdi, frag_or_rax_rbx
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .loop
.done:
    ret

cg_expr_and:
    call cg_expr_compare
.loop:
    call cg_tok_type
    cmp al, TOK_KEYWORD
    jne .done
    extern kw_and
    lea rdi, [kw_and]
    mov rsi, 3
    call cg_is_kw
    cmp rax, 1
    jne .done
    call cg_advance          ; consume 'and'
    call cg_expr_compare
    ; pop b, pop a, and => (a != 0) && (b != 0)
    ; Simple: test both, if either 0 result is 0
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_and_rax_rbx
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .loop
.done:
    ret

cg_expr_compare:
    call cg_expr_add

    ; Check for 'in' or 'is' keyword
    call cg_tok_type
    cmp al, TOK_KEYWORD
    jne .not_in_kw
    extern kw_in
    lea rdi, [kw_in]
    mov rsi, 2
    call cg_is_kw
    cmp rax, 1
    je .do_in
    extern kw_is
    lea rdi, [kw_is]
    mov rsi, 2
    call cg_is_kw
    cmp rax, 1
    je .do_is
    ; Word-based comparison operators for children
    extern kw_equals
    lea rdi, [kw_equals]
    mov rsi, 6
    call cg_is_kw
    cmp rax, 1
    je .do_word_eq
    extern kw_isnt
    lea rdi, [kw_isnt]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .do_word_neq
    extern kw_above
    lea rdi, [kw_above]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .do_word_gt
    extern kw_below
    lea rdi, [kw_below]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .do_word_lt
    extern kw_atleast
    lea rdi, [kw_atleast]
    mov rsi, 7
    call cg_is_kw
    cmp rax, 1
    je .do_word_gte
    extern kw_atmost
    lea rdi, [kw_atmost]
    mov rsi, 6
    call cg_is_kw
    cmp rax, 1
    je .do_word_lte
.not_in_kw:

    ; Check for comparison operators
    call cg_tok_type
    cmp al, TOK_OP
    jne .done
    call cg_tok_sub
    cmp al, OP_EQ
    je .cmp
    cmp al, OP_NEQ
    je .cmp
    cmp al, OP_LT
    je .cmp
    cmp al, OP_GT
    je .cmp
    cmp al, OP_LTE
    je .cmp
    cmp al, OP_GTE
    je .cmp
    jmp .done

.cmp:
    call cg_peek
    movzx r8d, byte [rax + 1]  ; save op subtype
    call cg_advance
    call cg_expr_add

    ; Pop right (rbx), pop left (rax), compare
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    ; cmp rax, rbx (left cmp right)
    mov rdi, frag_cmp_rax_rbx2
    call out_str

    ; setCC al
    cmp r8d, OP_EQ
    je .sete
    cmp r8d, OP_NEQ
    je .setne
    cmp r8d, OP_LT
    je .setl
    cmp r8d, OP_GT
    je .setg
    cmp r8d, OP_LTE
    je .setle
    jmp .setge2
.sete:
    mov rdi, frag_sete
    jmp .setdone
.setne:
    mov rdi, frag_setne
    jmp .setdone
.setl:
    mov rdi, frag_setl
    jmp .setdone
.setg:
    mov rdi, frag_setg
    jmp .setdone
.setle:
    mov rdi, frag_setle
    jmp .setdone
.setge2:
    mov rdi, frag_setge
.setdone:
    call out_str
    mov rdi, frag_movzx_eax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_in:
    call cg_advance          ; consume 'in'
    call cg_expr_add         ; evaluate RHS (array)
    ; Stack: [value, array]
    ; Pop array into rdi, pop value into rsi
    mov rdi, frag_pop_rdi
    call out_str
    mov rdi, frag_pop_rsi
    call out_str
    ; Call rt_arr_contains(rdi=array, rsi=value)
    mov rdi, frag_call_arr_contains
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_is:
    call cg_advance          ; consume 'is'
    call cg_expr_add         ; evaluate RHS (string)
    ; Stack: [left_str, right_str]
    ; Pop right into rsi, pop left into rdi
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_pop_rdi
    call out_str
    ; Call rt_str_eq(rdi=s1, rsi=s2) → rax=1/0
    mov rdi, frag_call_str_eq
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

; Word-based comparison operators — emit integer compare + setCC
; each: advance keyword, eval RHS, pop rbx/rax, cmp, set, push

.do_word_eq:
    call cg_advance
    call cg_expr_add
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_rbx2
    call out_str
    mov rdi, frag_sete
    call out_str
    mov rdi, frag_movzx_eax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_word_neq:
    call cg_advance
    call cg_expr_add
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_rbx2
    call out_str
    mov rdi, frag_setne
    call out_str
    mov rdi, frag_movzx_eax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_word_gt:
    call cg_advance
    call cg_expr_add
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_rbx2
    call out_str
    mov rdi, frag_setg
    call out_str
    mov rdi, frag_movzx_eax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_word_lt:
    call cg_advance
    call cg_expr_add
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_rbx2
    call out_str
    mov rdi, frag_setl
    call out_str
    mov rdi, frag_movzx_eax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_word_gte:
    call cg_advance
    call cg_expr_add
    mov rdi, frag_pop_rbx
    call out_str
    mov rdi, frag_pop_rax
    call out_str
    mov rdi, frag_cmp_rax_rbx2
    call out_str
    mov rdi, frag_setge
    call out_str
    mov rdi, frag_movzx_eax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .done

.do_word_lte:
    call cg_advance
