    xor r14, r14
    call codegen_call_args
    mov rdi, frag_call_substr
    call out_str
    mov rdi, frag_push_rax
    call out_str
    pop rsi
    pop rcx
    ret

; ---- Built-in: exit(code) — exit with status code ----
.builtin_exit:
    xor r14, r14
    call codegen_call_args
    mov rdi, frag_call_exit
    call out_str
    pop rsi
    pop rcx
    ret

.load_var_reg:
    ; Register variable first (deferred from .ident)
    mov rsi, [rsp]           ; name ptr
    mov ecx, [rsp + 8]       ; name len
    call register_var
.load_var:
    ; Load variable: mov rax, [_v_name] / push rax
    mov rdi, frag_mov_rax_bracket
    call out_str
    pop rsi
    pop rcx
    push rcx
    push rsi
    call out_var_name
    mov rdi, frag_close
    call out_str
    mov rdi, frag_push_rax
    call out_str
    pop rsi
    pop rcx

    ; Check for subscript: var[expr] (works for arrays and strings)
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .check_method
    call cg_tok_sub
    cmp al, PUNCT_LBRACKET
    jne .check_method
    ; Subscript (auto-detects string vs array at runtime)
    call cg_advance          ; consume '['
    call codegen_expr         ; index expression → push index
    call cg_advance          ; consume ']'
    ; Stack: [value_ptr, index]
    mov rdi, frag_call_subscript
    call out_str
    jmp .check_method        ; allow chaining: str[i].upper()

.check_method:
    ; Check for method call: .method()
    call cg_tok_type
    cmp al, TOK_DOT
    jne .load_var_done
    call cg_advance          ; consume '.'

    ; Get method name
    call cg_peek
    mov rsi, [rax + 8]       ; method name ptr
    mov ecx, [rax + 4]       ; method name len
    push rcx
    push rsi
    call cg_advance          ; consume method name

    ; Consume '('
    call cg_advance

    ; Pop the object into rdi (first arg)
    mov rdi, frag_pop_rdi
    call out_str

    ; Check method name and dispatch
    pop rsi
    pop rcx

    ; "upper" (5 chars)
    cmp ecx, 5
    jne .not_method_upper
    cmp byte [rsi], 'u'
    jne .not_method_upper
    cmp byte [rsi+4], 'r'
    jne .not_method_upper
    ; Consume ')' and emit call rt_str_upper
    call cg_advance
    mov rdi, frag_call_upper
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method        ; support chaining
.not_method_upper:

    ; "lower" (5 chars)
    cmp ecx, 5
    jne .not_method_lower
    cmp byte [rsi], 'l'
    jne .not_method_lower
    cmp byte [rsi+4], 'r'
    jne .not_method_lower
    call cg_advance
    mov rdi, frag_call_lower
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method        ; support chaining
.not_method_lower:

    ; "trim" (4 chars)
    cmp ecx, 4
    jne .not_method_trim
    cmp byte [rsi], 't'
    jne .not_method_trim
    cmp byte [rsi+3], 'm'
    jne .not_method_trim
    call cg_advance
    mov rdi, frag_call_trim
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method        ; support chaining
.not_method_trim:

    ; "contains" (8 chars) — needs 1 arg
    cmp ecx, 8
    jne .not_method_contains
    cmp byte [rsi], 'c'
    jne .not_method_contains
    ; Evaluate arg into rsi
    push rdi                 ; save frag_pop_rdi already emitted
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    pop rdi                  ; (dummy pop)
    mov rdi, frag_call_contains
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method        ; support chaining
.not_method_contains:

    ; "equals" (6 chars) — string equality check
    cmp ecx, 6
    jne .not_method_equals
    cmp byte [rsi], 'e'
    jne .not_method_equals
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_call_str_eq
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_equals:

    ; "replace" (7 chars) — needs 2 args
    cmp ecx, 7
    jne .not_method_replace
    cmp byte [rsi], 'r'
    jne .not_method_replace
    ; Evaluate old string arg
    call codegen_expr
    call cg_advance          ; consume ','
    ; Evaluate new string arg
    call codegen_expr
    call cg_advance          ; consume ')'
    ; Stack: [obj_ptr, old_ptr, new_ptr]
    ; Pop new into rdx, old into rsi
    mov rdi, frag_pop_rdx
    call out_str
    mov rdi, frag_pop_rsi
    call out_str
    ; rdi already set by frag_pop_rdi emitted above
    mov rdi, frag_call_replace
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method        ; support chaining
.not_method_replace:

    ; "len" (3 chars) — method style s.len()
    cmp ecx, 3
    jne .not_method_len
    cmp byte [rsi], 'l'
    jne .not_method_len
    call cg_advance
    mov rdi, frag_call_len
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_len:

    ; "startswith" (10 chars) — s.startswith("prefix")
    cmp ecx, 10
    jne .not_method_startswith
    cmp byte [rsi], 's'
    jne .not_method_startswith
    cmp byte [rsi+6], 'w'
    jne .not_method_startswith
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_call_startswith
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_startswith:

    ; "endswith" (8 chars) — s.endswith("suffix")
    cmp ecx, 8
    jne .not_method_endswith
    cmp byte [rsi], 'e'
    jne .not_method_endswith
    cmp byte [rsi+4], 'w'
    jne .not_method_endswith
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_call_endswith
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_endswith:

    ; "index" (5 chars) — s.index("sub")
    cmp ecx, 5
    jne .not_method_index
    cmp byte [rsi], 'i'
    jne .not_method_index
    cmp byte [rsi+1], 'n'
    jne .not_method_index
    cmp byte [rsi+2], 'd'
    jne .not_method_index
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_call_str_index
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_index:

    ; "split" (5 chars) — s.split(",")
    cmp ecx, 5
    jne .not_method_split
    cmp byte [rsi], 's'
    jne .not_method_split
    cmp byte [rsi+1], 'p'
    jne .not_method_split
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_call_split
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_split:

    ; "repeat" (6 chars) — s.repeat(3)
    cmp ecx, 6
    jne .not_method_repeat
    cmp byte [rsi], 'r'
    jne .not_method_repeat
    cmp byte [rsi+1], 'e'
    jne .not_method_repeat
    cmp byte [rsi+2], 'p'
    jne .not_method_repeat
    call codegen_expr
    call cg_advance          ; consume ')'
    mov rdi, frag_pop_rsi
    call out_str
    mov rdi, frag_call_str_repeat
    call out_str
    mov rdi, frag_push_rax
    call out_str
    jmp .check_method
.not_method_repeat:

    ; Unknown method — push 0
    call cg_advance          ; consume ')'
    mov rdi, frag_xor_rax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    ret

.load_var_done:
    ret

.keyword:
    ; true = 1, false = 0, null = 0
    extern kw_true
    lea rdi, [kw_true]
    mov rsi, 4
    call cg_is_kw
    cmp rax, 1
    je .push_1
    extern kw_false
    lea rdi, [kw_false]
    mov rsi, 5
    call cg_is_kw
    cmp rax, 1
    je .push_0
    ; null or other
    call cg_advance
.push_0:
    call cg_advance
    mov rdi, frag_xor_rax
    call out_str
    mov rdi, frag_push_rax
    call out_str
    ret
.push_1:
    call cg_advance
    mov rdi, frag_push_1
    call out_str
    ret
    call out_str
    ret

.paren:
    call cg_tok_sub
    cmp al, PUNCT_LPAREN
    jne .bracket
    call cg_advance          ; consume '('
    call codegen_expr
    call cg_advance          ; consume ')'
    ret
.bracket:
    cmp al, PUNCT_LBRACKET
    jne .paren_done
    ; Array literal [expr, expr, ...]
    call cg_advance          ; consume '['

    ; Create new array: xor rdi, rdi / call rt_arr_new / push rax
    mov rdi, frag_arr_new
    call out_str

    ; Check for empty array
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .arr_elem
    call cg_tok_sub
    cmp al, PUNCT_RBRACKET
    je .arr_done

.arr_elem:
    ; Evaluate element expression
    call codegen_expr
    ; Pop element into rsi, pop array into rdi
    ; call rt_arr_push, push rax (updated array)
    mov rdi, frag_arr_push_elem
    call out_str

    ; Check for comma
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .arr_done
    call cg_tok_sub
    cmp al, PUNCT_COMMA
    jne .arr_check_close
    call cg_advance          ; consume ','
    jmp .arr_elem
.arr_check_close:
    cmp al, PUNCT_RBRACKET
    jne .arr_done
.arr_done:
    call cg_advance          ; consume ']'
    ; Array pointer is on stack
.paren_done:
    ret

; ============================================================
; codegen_call_args — Evaluate function call arguments
; Expects: '(' already consumed, r14 = 0 (arg count init)
; Evaluates each arg expression (pushes result on stack)
; Then emits pops into SysV ABI registers based on arg count
; Preserves: r12, r13 (caller's name/len)
; Returns: r14 = arg count
; ============================================================
codegen_call_args:
    push rbp
    mov rbp, rsp
    push r12
    push r13
    push r14
    xor r14, r14

    ; Check for immediate ')' — no args
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .ca_eval_arg
    call cg_tok_sub
    cmp al, PUNCT_RPAREN
    je .ca_args_done

.ca_eval_arg:
    call codegen_expr
    inc r14

    ; Check for comma or rparen
    call cg_tok_type
    cmp al, TOK_PUNCT
    jne .ca_args_done
    call cg_tok_sub
    cmp al, PUNCT_COMMA
    jne .ca_check_rparen
    call cg_advance          ; consume ','
    jmp .ca_eval_arg
.ca_check_rparen:
    cmp al, PUNCT_RPAREN
    jne .ca_args_done
.ca_args_done:
    call cg_advance          ; consume ')'

    ; Zero unused arg registers (for default parameter support)
    mov r12, r14              ; r12 = loop counter, starts at arg count
.ca_zero_loop:
    cmp r12, 6
    jge .ca_zero_done
    mov rdi, [xor_reg_table + r12 * 8]
    call out_str
    inc r12
    jmp .ca_zero_loop
.ca_zero_done:

    ; Now emit pop cascade: args are on stack in order
    ; (first arg deepest), so we pop in reverse into registers.
    cmp r14, 6
    jge .ca_pop_6
    cmp r14, 5
    je .ca_pop_5
    cmp r14, 4
    je .ca_pop_4
    cmp r14, 3
    je .ca_pop_3
    cmp r14, 2
    je .ca_pop_2
    cmp r14, 1
    je .ca_pop_1
    jmp .ca_pop_done          ; 0 args
.ca_pop_6:
    mov rdi, frag_pop_r9
    call out_str
.ca_pop_5:
    mov rdi, frag_pop_r8
    call out_str
.ca_pop_4:
    mov rdi, frag_pop_rcx
    call out_str
.ca_pop_3:
    mov rdi, frag_pop_rdx
    call out_str
.ca_pop_2:
    mov rdi, frag_pop_rsi
    call out_str
.ca_pop_1:
    mov rdi, frag_pop_rdi
    call out_str
.ca_pop_done:
    ; Emit arg count in r10 (for variadic support)
    mov rdi, frag_mov_r10
    call out_str
    mov rdi, r14
    call out_int
    call out_str_newline

    pop r14
    pop r13
    pop r12
    pop rbp
    ret

; ============================================================
; codegen_write_file — Write output to file
; rdi = filename (null-terminated)
; ============================================================
global codegen_write_file
codegen_write_file:
    push rbp
    mov rbp, rsp

    mov rax, 2              ; sys_open
    mov rsi, 577            ; O_WRONLY | O_CREAT | O_TRUNC
    mov rdx, 0644o
    syscall
    cmp rax, 0
    jl .error
    mov [out_fd], rax

    mov rax, 1              ; sys_write
    mov rdi, [out_fd]
    mov rsi, out_buf
    mov rdx, [out_pos]
    syscall

    mov rax, 3
    mov rdi, [out_fd]
    syscall

    xor rax, rax
    pop rbp
    ret
.error:
    mov rax, -1
    pop rbp
    ret
