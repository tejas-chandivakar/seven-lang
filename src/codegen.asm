; Instead of walking a complex AST, this codegen does a
; SINGLE-PASS direct code generation from the token stream.
; This avoids the parser's shared-buffer issues entirely.
;
; Features supported:
;   - Integer/string variables
;   - show (int and string print + newline)
;   - show.raw (no newline)
;   - err (to stderr)
;   - Math: + - * / // % **
;   - Comparisons: == != < > <= >=
;   - if / elif / else / end
;   - repeat N [times] [as i] / end
;   - while cond / end
;   - func name(params) / end + return
;   - Function calls name(args)
;   - String literals in .data
;   - ask "prompt" (input)
;   - comments (skipped)
;   - skip / stop (continue / break)
;
; Output: NASM assembly text that links with runtime.asm
; ============================================================

